"""A spine as a Python seed file — the programme "in the file", not only in the database.

The file :func:`render` writes has the same shape as
``core/academic_spine_sample.py``: a ``SPINE`` dict of plain literals and a
``seed()`` that builds it. Save it under ``core/`` with the pack under
``fixtures/`` and it re-creates the programme on any database::

    python manage.py seed_programme_pack core/academic_spine_<key>.py
"""

import datetime as dt
import pprint

HEADER = '''"""
{title} — the academic spine, generated by the programme-pack importer on {today}.

Institution {institution} → programme {programme} → cohort {cohort}.
Pack: {pack} ({files} files: {blocks} teaching blocks, {units} units, {mocks} mock sittings).

Edit the data below and re-run; every row is keyed on "{key}", so a re-run
corrects in place and never duplicates:

    python manage.py seed_programme_pack {module_path}
"""

'''

FOOTER = '''

def seed(**kwargs):
    """Build (or top up) this programme. Keyword arguments are the builder's."""
    from core.programme_pack import seed_spine
    return seed_spine(SPINE, **kwargs)
'''


def render(spine, *, plan_summary=None, pack_hint=None, module_path=None):
    """The seed file's source text."""
    spine = dict(spine)
    if pack_hint:
        spine['pack'] = pack_hint
    summary = plan_summary or {}
    head = HEADER.format(
        title=spine['programme'].get('full_name') or spine['programme']['code'],
        today=dt.date.today().isoformat(),
        institution=spine['institution']['code'], programme=spine['programme']['code'],
        cohort=spine['cohort'].get('name') or spine['cohort']['code'], pack=spine['pack'],
        files=summary.get('files', '?'), blocks=summary.get('blocks', '?'), units=summary.get('units', '?'),
        mocks=summary.get('mocks', '?'), key=spine['key'],
        module_path=module_path or f'core/academic_spine_{spine["key"]}.py')
    body = 'SPINE = ' + pprint.pformat(spine, width=110, sort_dicts=False) + '\n'
    return head + body + FOOTER


def load(path):
    """``SPINE`` from a seed file on disk (one this module wrote, or the IAC one)."""
    import importlib.util
    spec = importlib.util.spec_from_file_location('programme_spine', path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.SPINE
